CREATE TABLE IF NOT EXISTS biomie_jobs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  job_uuid CHAR(36) NOT NULL,
  idempotency_key VARCHAR(191) NOT NULL,
  queue_name VARCHAR(50) NOT NULL DEFAULT 'default',
  job_type VARCHAR(100) NOT NULL,
  payload_json JSON NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'queued',
  priority TINYINT NOT NULL DEFAULT 5,
  attempts INT NOT NULL DEFAULT 0,
  max_attempts INT NOT NULL DEFAULT 3,
  available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reserved_at DATETIME NULL,
  started_at DATETIME NULL,
  finished_at DATETIME NULL,
  failed_at DATETIME NULL,
  last_error TEXT NULL,
  error_summary VARCHAR(255) NULL,
  company_id INT NULL,
  created_by INT NULL,
  request_id VARCHAR(64) NULL,
  locked_by VARCHAR(100) NULL,
  locked_until DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

  PRIMARY KEY (id),
  UNIQUE KEY uq_biomie_jobs_uuid (job_uuid),
  UNIQUE KEY uq_biomie_jobs_idempotency (idempotency_key),
  KEY idx_biomie_jobs_claim (queue_name, status, priority, available_at, id),
  KEY idx_biomie_jobs_status (status, created_at),
  KEY idx_biomie_jobs_type (job_type, status, created_at),
  KEY idx_biomie_jobs_company (company_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
